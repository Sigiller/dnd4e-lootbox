/**
 * Fits a price for every box level from DEFAULT_MODEL, DEFAULT_TYPE_WEIGHTS and the pool fixture, prints the odds
 * table, and with --write rewrites src/model/prices.ts.
 *
 *   npm run calibrate [-- --write]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fitPrice, meetsTargets } from "../src/model/calibrate.js";
import { DEFAULT_MODEL, DEFAULT_TARGETS, DEFAULT_TYPE_WEIGHTS } from "../src/model/defaults.js";
import { boxDistribution } from "../src/model/distribution.js";
import { poolCellsFromRecord, poolPricesFromCells } from "../src/model/type-weights.js";

const record = JSON.parse(readFileSync(resolve("tests/fixtures/pool-prices.json"), "utf8")) as Record<string, unknown>;
const pool = poolPricesFromCells(poolCellsFromRecord(record), DEFAULT_TYPE_WEIGHTS);
const pct = (p: number): string => `${(p * 100).toFixed(1)}%`;

const prices: number[] = [];
let misses = 0;
console.log("| L | Price (gp) | Loss | Sell-profit | Avg value |");
console.log("|---|---|---|---|---|");
for (let level = 1; level <= 30; level++) {
  const { price, odds } = fitPrice(boxDistribution(DEFAULT_MODEL, pool, level), DEFAULT_TARGETS);
  prices.push(price);
  if (!meetsTargets(odds, DEFAULT_TARGETS)) misses++;
  console.log(
    `| ${String(level)} | ${price.toLocaleString("en-US")} | ${pct(odds.pLoss)} | ${pct(odds.pSellProfit)} | ${odds.valueRatio.toFixed(2)}× |${meetsTargets(odds) ? "" : " OFF TARGET"}`
  );
}
console.log(`\nlevels off target: ${String(misses)}`);

if (process.argv.includes("--write")) {
  const body = prices.map((price, index) => `  ${String(price)}, // L${String(index + 1)}`).join("\n");
  const header = [
    "// Generated by `npm run calibrate -- --write` from DEFAULT_MODEL, DEFAULT_TYPE_WEIGHTS and tests/fixtures/pool-prices.json.",
    "/** Default box price in gp per box level (index 0 = level 1). GMs override these in the module settings. */",
  ].join("\n");
  writeFileSync(
    resolve("src/model/prices.ts"),
    `${header}\nexport const DEFAULT_BOX_PRICES: readonly number[] = [\n${body}\n];\n`
  );
  console.log("wrote src/model/prices.ts");
}
